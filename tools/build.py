"""
Locks (encrypts) the private pages and photos so the public repo only holds scrambled files.

    set BIRTHDAY_PASSWORD=<the password>      (PowerShell:  $env:BIRTHDAY_PASSWORD="<the password>")
    python tools/build.py

Reads   private/days/*.html, private/days/dec01.js, private/days.js, private/images/**
Writes  vault/*.bin, vault/img/*.bin, vault/images.json, vault/salt.txt, vault/check.bin, themes.js
Run it again after every change in private/. The private/ folder is never uploaded (.gitignore).
"""
import hashlib, json, os, re, secrets, shutil, subprocess, sys
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)
ITER = 200_000

pw = os.environ.get("BIRTHDAY_PASSWORD")
if not pw:
    sys.exit("Set BIRTHDAY_PASSWORD first (see the top of this file).")
pw = re.sub(r"\s+", "", pw.lower())  # same as the website: capitals and spaces don't matter

vault = P("vault")
salt_file = os.path.join(vault, "salt.txt")
salt = bytes.fromhex(open(salt_file).read().strip()) if os.path.exists(salt_file) else secrets.token_bytes(16)
shutil.rmtree(vault, ignore_errors=True)
os.makedirs(os.path.join(vault, "img"), exist_ok=True)
open(salt_file, "w").write(salt.hex())

key = hashlib.pbkdf2_hmac("sha256", pw.encode(), salt, ITER, 32)
aes = AESGCM(key)

def seal(data: bytes, out: str):
    iv = secrets.token_bytes(12)
    with open(out, "wb") as f:
        f.write(iv + aes.encrypt(iv, data, None))

seal(b"ok", os.path.join(vault, "check.bin"))

# ---- pages
days_js = open(P("private", "days.js"), encoding="utf-8").read()
dec01_js = open(P("private", "days", "dec01.js"), encoding="utf-8").read()
for name in sorted(os.listdir(P("private", "days"))):
    if not name.endswith(".html"):
        continue
    html = open(P("private", "days", name), encoding="utf-8").read()
    html = re.sub(r'\s*<script src="\.\./common/guard\.js"></script>', "", html)
    html = html.replace('href="../style.css"', 'href="style.css"')
    html = html.replace('<script src="../days.js"></script>', "<script>\n" + days_js + "\n</script>")
    html = html.replace('<script src="dec01.js"></script>', "<script>\n" + dec01_js + "\n</script>")
    seal(html.encode("utf-8"), os.path.join(vault, name[:-5] + ".bin"))
    print("page ", name)

# ---- images
TYPES = {".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".gif": "image/gif"}
index = {}
for dirpath, _, files in os.walk(P("private", "images")):
    for fn in sorted(files):
        ext = os.path.splitext(fn)[1].lower()
        if ext not in TYPES:
            continue
        rel = os.path.relpath(os.path.join(dirpath, fn), P("private")).replace("\\", "/")  # images/gallery/p01.jpg
        out = "img/" + rel[len("images/"):].replace("/", "_") + ".bin"
        seal(open(os.path.join(dirpath, fn), "rb").read(), os.path.join(vault, out))
        index["../" + rel] = {"f": out, "t": TYPES[ext]}
json.dump(index, open(os.path.join(vault, "images.json"), "w"), indent=0)
print("images", len(index))

# ---- public theme data (colours + dates only, no messages)
node = r"""
const fs=require('fs');eval(fs.readFileSync(process.argv[1],'utf8')+';global.D=DAYS;global.DT=DEFAULT_THEME');
const keep=['date','name','font','accent','accent2','accent3','soft','bgA','bgB','bgC','text','deep','strong','btnText','hearts','birthday'];
const pick=o=>Object.fromEntries(Object.entries(o).filter(([k])=>keep.includes(k)));
process.stdout.write('// generated by tools/build.py (colours only, no messages)\nconst DEFAULT_THEME = '+JSON.stringify(pick(DT))+';\nconst DAYS = '+JSON.stringify(D.map(pick),null,1)+';\n');
"""
out = subprocess.run(["node", "-e", node, P("private", "days.js")], capture_output=True, text=True, encoding="utf-8", check=True).stdout
open(P("themes.js"), "w", encoding="utf-8").write(out)
print("themes.js written. Done.")
